import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';

const sourceUrl=new URL('../src/engine.ts',import.meta.url);
const outputUrl=new URL('../src/browser-guards.generated.ts',import.meta.url);
const source=ts.createSourceFile('engine.ts',fs.readFileSync(sourceUrl,'utf8'),ts.ScriptTarget.Latest,true);
const guards={};
for(const name of ['blockedRoute','sharedFromMessages']){
 const declaration=source.statements.find(node=>ts.isFunctionDeclaration(node)&&node.name?.text===name);
 assert.ok(declaration,'Missing browser guard '+name);
 guards[name]=ts.transpileModule(declaration.getText(source).replace(/^export /,''),{
  compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.None,alwaysStrict:false},
 }).outputText.trim();
}
const output='// Generated by npm run generate:browser-guards; keep function source outside Hermes bytecode.\nexport const browserGuardSources = '+JSON.stringify(guards,null,2)+' as const;\n';
if(process.argv.includes('--check')){
 assert.equal(fs.readFileSync(outputUrl,'utf8'),output,'Browser guards are stale. Run npm run generate:browser-guards.');
}else fs.writeFileSync(outputUrl,output);
